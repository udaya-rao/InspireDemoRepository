// Permission checking utility functions
import React from 'react';
export const hasPermission = (requiredPermissionId) => {
  try {
    const userStr = localStorage.getItem('user');
    if (!userStr) return false;

    const parsed = JSON.parse(userStr);
    const userObj = Array.isArray(parsed) ? (parsed[0] || {}) : parsed;
    const userPermissions = userObj.rule_ids || userObj.permissions || userObj.accessIds || [];

    // Convert to array if it's not already
    const permissionsArray = Array.isArray(userPermissions) ? userPermissions : [userPermissions];

    return permissionsArray.includes(requiredPermissionId);
  } catch (error) {
    console.error('Error checking permission:', error);
    return false;
  }
};

// Check multiple permissions (OR logic - user needs any one of the permissions)
export const hasAnyPermission = (permissionIds) => {
  return permissionIds.some(id => hasPermission(id));
};

// Check multiple permissions (AND logic - user needs all permissions)
export const hasAllPermissions = (permissionIds) => {
  return permissionIds.every(id => hasPermission(id));
};

