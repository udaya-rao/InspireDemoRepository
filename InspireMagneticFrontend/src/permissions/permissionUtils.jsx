// Reusable component for conditional rendering based on permissions
export const PermissionGuard = ({ permission, fallback = null, children }) => {
  const hasAccess = hasPermission(permission);
  return hasAccess ? children : fallback;
};

// Hook for checking permissions in components
export const usePermission = (permissionId) => {
  const [hasAccess, setHasAccess] = React.useState(false);

  React.useEffect(() => {
    setHasAccess(hasPermission(permissionId));
  }, [permissionId]);

  return hasAccess;
};

// Hook for checking multiple permissions
export const usePermissions = (permissionIds, logic = 'any') => {
  const [hasAccess, setHasAccess] = React.useState(false);

  React.useEffect(() => {
    if (logic === 'all') {
      setHasAccess(hasAllPermissions(permissionIds));
    } else {
      setHasAccess(hasAnyPermission(permissionIds));
    }
  }, [permissionIds, logic]);

  return hasAccess;
}; 